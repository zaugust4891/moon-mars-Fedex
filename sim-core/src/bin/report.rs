//! Generates the Phase 10 engineering report (markdown to stdout).
//! Run: cargo run --release --bin report

use sim_core::analyzer::{compare_all, monte_carlo, sensitivity};
use sim_core::constants::*;
use sim_core::patched_conic::{budget, MissionParams, TargetOrbit};
use sim_core::trajectory::nbody_check;

fn t(x: f64) -> String {
    format!("{:.1}", x / 1000.0) // kg -> t
}

fn main() {
    let p = MissionParams::default();
    let b = budget(&p);

    println!("# Simulation Results — 45,359 kg (100,000 lb), Lunar Surface → {}\n", p.target.label());
    println!("Generated by `sim-core` v0.1.0 (`cargo run --release --bin report`). All values from the analytic engine; assumptions in docs/02.\n");

    println!("## Mission Δv budget (impulsive reference, unmargined)\n");
    println!("| Segment | Δv (km/s) | Notes |");
    println!("|---|---|---|");
    println!("| Lunar ascent (surface → 100 km LLO) | {:.3} | v_LLO {:.3} + gravity/steering loss |", b.ascent, b.v_llo);
    println!("| Trans-Mars injection (from LLO) | {:.3} | Oberth burn; v∞,Earth = {:.3} km/s |", b.tmi, b.vinf_dep);
    println!("| Midcourse / plane change | {:.3} | Mars i = 1.85° mostly absorbed at departure |", b.midcourse);
    println!("| Mars orbit insertion | {:.3} | v∞,Mars = {:.3} km/s, capture at {:.0} km radius |", b.moi, b.vinf_arr, b.capture_rp_km);
    println!("| Rendezvous trim | {:.3} | terminal phasing for orbiter intercept |", b.rendezvous);
    println!("| **Total** | **{:.3}** | with 5% margin: {:.3} |", b.total, b.total_margined);
    println!();
    println!("Transfer: Hohmann, TOF **{:.1} days**, departure lead angle **{:.1}°**, synodic window every **{:.1} days**.\n", b.tof_days, b.lead_angle_deg, b.synodic_days);

    {
        let mut p1 = p;
        p1.target = TargetOrbit::OneSolEllipse { peri_alt_km: 300.0 };
        let b1 = budget(&p1);
        println!("Alternate target (1-sol ellipse): MOI drops to {:.3} km/s, total {:.3} km/s.\n", b1.moi, b1.total);
    }

    let (dev, _, _) = nbody_check(&b);
    println!("Patched-conic vs restricted N-body (RKF45, tol 1 km/step): arrival deviation **{:.2}M km** ({:.2}% of transfer arc), dominated by along-track timing (Mars moves 1.3M km/day). In a real mission this is absorbed by departure targeting, not Δv; the patched-conic Δv budget itself is accurate to <1%.\n", dev / 1e6, dev / (core::f64::consts::PI * b.transfer.a_t) * 100.0);

    println!("## Propulsion architecture comparison\n");
    println!("| System | Feasible | Wet mass (t) | Propellant (t) | Δv prop. (km/s) | Transit (d) | Peak g | Power | Energy (GJ) | $/kg | TRL |");
    println!("|---|---|---|---|---|---|---|---|---|---|---|");
    let results = compare_all(&p);
    for r in &results {
        let power = if r.power_kw > 1e6 {
            format!("{:.1} GW(jet)", r.power_kw / 1e6)
        } else if r.power_kw > 1000.0 {
            format!("{:.1} MW", r.power_kw / 1000.0)
        } else {
            format!("{:.0} kW", r.power_kw)
        };
        println!(
            "| {}{} | {} | {} | {} | {:.2}{} | {:.0} | {:.1} | {} | {:.0} | {:.0} | {} |",
            r.sys.name,
            if r.sys.speculative { " ⚠" } else { "" },
            if r.feasible { "✅" } else { "❌" },
            t(r.wet_mass_kg),
            t(r.prop_mass_kg),
            r.total_dv_kms,
            if r.kinetic_dv_kms > 0.0 { format!(" (+{:.2} kinetic)", r.kinetic_dv_kms) } else { String::new() },
            r.transit_days,
            r.peak_accel_g,
            power,
            r.energy_gj,
            r.cost.usd_per_kg,
            r.sys.trl,
        );
    }
    println!("\nWet mass = total flight-system mass leaving the lunar surface (cargo included). $/kg amortizes dev+infra over 20 missions.\n");

    for r in &results {
        if let Some(l) = &r.launcher {
            println!("### {} — launcher details", r.sys.name);
            println!("- muzzle velocity {:.2} km/s, track {:.0} m at {:.0} g, launch {:.2} s", l.muzzle_v_kms, l.track_length_m, l.peak_accel_g, l.launch_duration_s);
            println!("- {:.1} GJ electrical per launch ({:.1} MWh); {:.1} MW average recharge for 1 launch/day\n", l.launch_energy_gj, l.launch_energy_gj / 3.6, l.recharge_power_mw);
        }
    }

    println!("## Monte Carlo dispersions (n=2000, seed 42; 1σ: Isp 1%, structure 8%, margin 2%)\n");
    println!("| System | Feasible runs | Wet mean (t) | p5 (t) | p50 (t) | p95 (t) |");
    println!("|---|---|---|---|---|---|");
    for id in [0u32, 2, 6, 7] {
        let mc = monte_carlo(id, &p, 2000, 42);
        let name = results.iter().find(|r| r.sys.id == id).map(|r| r.sys.name).unwrap_or("?");
        println!("| {} | {:.1}% | {} | {} | {} | {} |", name, mc.feasible_frac * 100.0, t(mc.wet_mean), t(mc.wet_p5), t(mc.wet_p50), t(mc.wet_p95));
    }

    println!("\n## Sensitivity (Lunar LOX/LH2)\n");
    println!("| Parameter | Low | Wet (t) | $/kg | High | Wet (t) | $/kg |");
    println!("|---|---|---|---|---|---|---|");
    for row in sensitivity(0, &p) {
        println!(
            "| {} | {} | {} | {:.0} | {} | {} | {:.0} |",
            row.param, row.low_label, t(row.wet_low), row.cost_low, row.high_label, t(row.wet_high), row.cost_high
        );
    }

    println!("\n## Ranking among feasible, non-speculative systems\n");
    let mut feas: Vec<_> = results.iter().filter(|r| r.feasible && !r.sys.speculative).collect();
    feas.sort_by(|a, b| a.cost.usd_per_kg.partial_cmp(&b.cost.usd_per_kg).unwrap());
    println!("By cost per delivered kg:");
    for (i, r) in feas.iter().enumerate() {
        println!("{}. {} — ${:.0}/kg, {:.1} t wet, {:.0} d transit, TRL {}", i + 1, r.sys.name, r.cost.usd_per_kg, r.wet_mass_kg / 1000.0, r.transit_days, r.sys.trl);
    }
    feas.sort_by(|a, b| a.wet_mass_kg.partial_cmp(&b.wet_mass_kg).unwrap());
    println!("\nBy flight mass (lunar logistics burden):");
    for (i, r) in feas.iter().enumerate() {
        println!("{}. {} — {:.1} t", i + 1, r.sys.name, r.wet_mass_kg / 1000.0);
    }
    println!("\nCargo: {:.0} kg. G0 = {} m/s². Engine: sim-core (Rust), analytic + RKF45.", CARGO_DEFAULT_KG, G0);
}
